"""Application-defined storage contract; no SQLite knowledge in business logic."""
from __future__ import annotations

from typing import Any, Protocol, runtime_checkable

from ..domain.contracts import State, TaskSpec


@runtime_checkable
class TaskRepository(Protocol):
    """Minimum durable operations required by task execution and action policy."""

    def create(self, spec: TaskSpec) -> dict[str, Any]: ...
    def get(self, task_id: str) -> dict[str, Any]: ...
    def claim_admission(self, task_id: str) -> bool: ...
    def transition(
        self, task_id: str, new: State, data: dict | None = None,
        *, owner: str | None = None,
    ) -> dict[str, Any]: ...
    def lease(self, task_id: str, worker: str, now: float, seconds: float = 60) -> bool: ...
    def release(self, task_id: str, worker: str) -> None: ...
    def quarantine(self, task_id: str, reason: str, *, owner: str | None = None) -> None: ...
    def record_approval(self, approval_id: str, task_id: str, digest: str, ttl: int) -> None: ...
    def grant_approval_record(self, approval_id: str) -> None: ...
    def authorize_action_record(
        self, digest: str, task_id: str, kind: str, *,
        requires_approval: bool, approval_id: str | None,
    ) -> None: ...
    def finalize_action_record(self, digest: str, outcome: dict, *, verified: bool) -> None: ...
